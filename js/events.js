// Ценовая категория по цене
function priceBand(price) {
  if (price === 0) return 'free';
  if (price <= 1000) return 'low';
  if (price <= 2500) return 'mid';
  return 'high';
}

// Тарифы события (вычисляются из базовой цены)
function tariffsOf(e) {
  const round50 = n => Math.round(n / 50) * 50;
  if (e.format === 'online') {
    if (e.price === 0) {
      return [{ id: 'free', name: 'Бесплатный доступ', price: 0, note: 'прямой эфир, нужна запись' }];
    }
    return [
      { id: 'online', name: 'Онлайн-доступ', price: e.price, note: 'прямой эфир' },
      { id: 'online-rec', name: 'Доступ + запись', price: round50(e.price * 1.5), note: 'эфир и запись на 30 дней' }
    ];
  }
  if (e.price === 0) {
    return [{ id: 'free', name: 'Свободный вход', price: 0, note: 'по предварительной записи' }];
  }
  return [
    { id: 'std', name: 'Стандарт', price: e.price, note: 'основная зона' },
    { id: 'disc', name: 'Льготный', price: round50(e.price * 0.7), note: 'студенты, пенсионеры, многодетные семьи' },
    { id: 'vip', name: 'VIP', price: e.price * 2, note: 'лучшие места и приветственный напиток' }
  ];
}

